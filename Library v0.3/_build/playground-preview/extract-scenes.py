#!/usr/bin/env python3
"""Writes src/scenes/<pattern>.tsx from the Nucleux catalog's "As on nucleux.in"
code (get_component output saved as <Component>.md) and src/scenes/index.ts,
the pattern-id -> scene registry the preview loads.

    python3 extract-scenes.py <folder with Md3*.md files>
"""
import os, re, sys

# Playground pattern id -> its Material 3 component in @nucleux/react
MAP = {
    "disclosure": "Md3Disclosure", "consent": "Md3Consent", "caveat": "Md3Caveat",
    "avatar": "Md3AgentAvatar", "name": "Md3AgentName", "personality": "Md3Personality",
    "iconography": "Md3Iconography", "color": "Md3AiColor", "example-gallery": "Md3ExampleGallery",
    "templates": "Md3Templates", "nudges": "Md3Nudge", "disclaimer": "Md3Disclaimer",
    "suggestions": "Md3Suggestions", "madlibs": "Md3Madlibs", "prompt-enhancer": "Md3PromptEnhancer",
    "modes": "Md3Modes", "voice-tone": "Md3VoiceTone", "preset-styles": "Md3PresetStyles",
    "initial-cta": "Md3InitialCta", "open-input": "Md3OpenInput", "suggested-prompts": "Md3SuggestedPrompts",
    "ai-icons": "Md3AiIcons", "autocomplete": "Md3Autocomplete", "proactive": "Md3ProactiveSuggestion",
    "randomize": "Md3Randomize", "attachments": "Md3Attachments", "model-selection": "Md3ModelSelection",
    "connectors": "Md3Connector", "mcp": "Md3McpConnection", "knowledge-base": "Md3KnowledgeBase",
    "voice-input": "Md3VoiceInput", "visual-input": "Md3VisualInput", "handwriting": "Md3HandwritingInput",
    "gesture": "Md3GestureInput", "structured-input": "Md3StructuredInput",
}

src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "scenes")
os.makedirs(out, exist_ok=True)
done, missing = [], []
for pid, comp in MAP.items():
    path = os.path.join(src, comp + ".md")
    if not os.path.exists(path):
        missing.append((pid, comp, "no file")); continue
    text = open(path, encoding="utf-8").read()
    i = text.find("## As on nucleux.in")
    m = re.search(r"```tsx\n(.*?)```", text[i:], re.S) if i >= 0 else None
    if not m or "SitePreview" not in m.group(1):
        missing.append((pid, comp, "no As-on-nucleux.in code")); continue
    code = m.group(1)
    head = f"/* {comp} — \"As on nucleux.in\" from the Nucleux catalog (@nucleux/react 0.12.0), kept as published. */\n"
    open(os.path.join(out, pid + ".tsx"), "w", encoding="utf-8").write(head + code)
    done.append(pid)

lines = ["/* Pattern id -> its Material 3 scene. Generated by extract-scenes.py; each loads on demand. */",
         "import type * as React from \"react\";",
         "type Scene = () => Promise<{ SitePreview: React.ComponentType }>;",
         "export const SCENES: Record<string, Scene> = {"]
lines += [f'  "{pid}": () => import("./{pid}"),' for pid in done]
lines += ["};", ""]
open(os.path.join(out, "index.ts"), "w").write("\n".join(lines))
print("scenes:", len(done), "| missing:", missing)
