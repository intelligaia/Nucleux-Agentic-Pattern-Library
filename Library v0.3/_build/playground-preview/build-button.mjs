/* Builds ../../nx-button.css: the Nucleux Button for plain-HTML pages.
   The token variables (only the :root blocks of @nucleux/tokens, all
   --nx-* so they clash with nothing) plus the Button's utilities from
   tailwind.button.config.cjs. Use it as
     <span class="nx-scope"><a class="…Button classes…" href="…">…</a></span>
   with the classes the Button renders (get_component Button, html). */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const tokens = readFileSync("node_modules/@nucleux/tokens/dist/styles.css", "utf8");
const roots = tokens.split("}").filter((r) => r.trim().startsWith(":root{")).map((r) => r.trim() + "}");
const dir = mkdtempSync(join(tmpdir(), "nx-button-"));
writeFileSync(join(dir, "in.css"), "@tailwind utilities;\n");
execFileSync("npx", ["tailwindcss", "-c", "tailwind.button.config.cjs", "-i", join(dir, "in.css"), "-o", join(dir, "out.css"), "--minify"], { stdio: "inherit" });
/* Tailwind's preflight gives every element a solid zero-width border and
   border-box sizing; without it `border` would draw nothing. The same
   rule, kept to the scope (wrap each component, not a whole section). */
const base = ".nx-scope,.nx-scope *,.nx-scope ::before,.nx-scope ::after{box-sizing:border-box;border:0 solid hsl(var(--nx-border))}";
const out = "/* Generated by _build/playground-preview/build-button.mjs from @nucleux/button + @nucleux/tokens. Do not edit. */\n" +
  roots.join("") + base + readFileSync(join(dir, "out.css"), "utf8");
writeFileSync("../../nx-button.css", out);
console.log("nx-button.css", out.length, "bytes");
